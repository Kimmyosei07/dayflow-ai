import { Link } from 'react-router-dom';
import { Sparkles, PlugZap, RefreshCw } from 'lucide-react';
import { useAiStatus } from '../../context/AiStatusContext.jsx';
import { providerLabel } from '../../services/ai/providers/index.js';

/** Small pill showing which provider generated a piece of content. */
export function AiSourceBadge({ source, provider }) {
  if (source === 'ai') {
    return (
      <span className="badge badge--primary" title="Generated by AI">
        <Sparkles size={12} /> AI · {providerLabel(provider)}
      </span>
    );
  }
  return (
    <span className="badge" title="Calculated with built-in rules, not AI">
      Rule-based
    </span>
  );
}

/** Explains why AI is unavailable and how to enable it. */
export function AiSetupNotice({ compact = false }) {
  const { ready, reason, refresh, status } = useAiStatus();
  if (ready) return null;
  return (
    <div className="alert alert--primary">
      <PlugZap size={18} />
      <div className="grow">
        <strong>AI features are not active.</strong> {reason}
        {!compact && (
          <span>
            {' '}
            Everything else works without AI. See <Link to="/settings#ai">Settings → AI provider</Link> or the README for setup steps.
          </span>
        )}
      </div>
      <button type="button" className="btn btn--ghost btn--sm" onClick={refresh} disabled={status.loading} title="Check AI configuration again">
        <RefreshCw size={14} /> Recheck
      </button>
    </div>
  );
}
